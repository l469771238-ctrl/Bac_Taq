def tri(full):
    """أول 3 كلمات بس."""
    parts = str(full).split()
    return " ".join(parts[:3]) if len(parts) >= 3 else str(full)

rows, seen = [], set()
dups = []
for code, full in ROWS:
    if code.endswith('b'):
        dups.append((code, full)); continue
    if code in seen:
        dups.append((code, full)); continue
    seen.add(code)
    rows.append((code, tri(full)))

with open('students.csv', 'w', newline='', encoding='utf-8') as f:
    w = csv.writer(f)
    w.writerow(['code', 'name'])
    w.writerows(rows)

with open('students.json', 'w', encoding='utf-8') as f:
    json.dump([{'code': c, 'name': n} for c, n in rows], f, ensure_ascii=False, indent=1)

